#!/usr/bin/env node
/**
 * Generates design/theme.css for the marver design canvas.
 *
 * Why this exists: the app compiles with Tailwind 3 through tailwind.config.ts, and marver
 * compiles the canvas with the Tailwind 4 engine it bundles. A v4 engine cannot read a v3 JS
 * config, which is why the scaffolded theme.css failed with "Could not resolve value for theme
 * function" and every frame rendered as an error. Rather than hand-maintaining a second copy of
 * the palette (which would drift the first time a colour changed), this script emits the v4
 * @theme block from the same tokens.mjs the v3 config imports.
 *
 * Run it after changing tokens.mjs: npm run design:theme
 */
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { boxShadow, chart, colors, fontFamily, fontImportUrl, grainImage } from "../tokens.mjs"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

// The Tailwind 4 stylesheet marver compiles the canvas with, relative to design/theme.css.
const V4_ENTRY = "../node_modules/@tailwindcss/node/node_modules/tailwindcss/index.css"

/** Flattens { violet: { DEFAULT, light } } into the --color-violet / --color-violet-light pairs
 *  Tailwind 4 expects, so `bg-violet` and `bg-violet-light` mean the same thing in both worlds. */
function colorVars(palette) {
  const out = []
  for (const [name, value] of Object.entries(palette)) {
    if (typeof value === "string") {
      out.push(`  --color-${name}: ${value};`)
      continue
    }
    for (const [shade, hex] of Object.entries(value)) {
      out.push(`  --color-${name}${shade === "DEFAULT" ? "" : `-${shade}`}: ${hex};`)
    }
  }
  return out
}

const lines = [
  "/* GENERATED by scripts/gen-marver-theme.mjs from tokens.mjs. Do not edit by hand:",
  " * the next run overwrites it. Change a token in tokens.mjs and re-run `npm run design:theme`,",
  " * and the app (Tailwind 3) and this canvas (Tailwind 4) move together. */",
  "",
  "/* The app declares these faces in index.html; the canvas has its own shell and never sees it. */",
  `@import url("${fontImportUrl}");`,
  "",
  "/* `@import \"tailwindcss\"` would resolve to the app's Tailwind 3, which ships no CSS entry",
  " * point: the v4 engine then fails with \"Can't resolve 'tailwindcss'\". marver bundles its own",
  " * v4 copy, so the canvas imports that one explicitly. */",
  `@import "${V4_ENTRY}";`,
  "",
  "/* The frames live here, so the v4 engine has to scan them for class names. */",
  '@source "./";',
  "",
  "@theme {",
  ...colorVars(colors),
  "",
  ...Object.entries(fontFamily).map(([name, stack]) => `  --font-${name}: ${stack.join(", ")};`),
  "",
  ...Object.entries(boxShadow).map(([name, value]) => `  --shadow-${name}: ${value};`),
  "}",
  "",
  "/* The plain-CSS values base.css reads by name. */",
  ":root {",
  `  --uc-violet: ${colors.violet.DEFAULT};`,
  `  --uc-ink: ${colors.ink};`,
  `  --uc-grain: ${grainImage};`,
  `  --uc-chart-grid: ${chart.grid};`,
  "}",
  "",
  "/* The app's own body rules, written out rather than @apply'd: this file is compiled by a",
  "   different Tailwind than the one that understands the app's config. */",
  "body {",
  `  background-color: ${colors.bg};`,
  "  color: #ffffff;",
  `  font-family: ${fontFamily.body.join(", ")};`,
  '  font-feature-settings: "ss01" 1;',
  "}",
  "",
  '@import "../src/styles/base.css";',
  "",
]

writeFileSync(join(root, "design/theme.css"), lines.join("\n"), "utf8")
console.log("design/theme.css generated from tokens.mjs")
